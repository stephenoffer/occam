"""Writes clients/orders_generated.py from api/orders.schema.json. Run from the repository root after changing the schema."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate(schema: dict) -> str:
    lines = ["# Code generated by tools/gen_client.py from api/orders.schema.json. DO NOT EDIT.", "",
             "from dataclasses import dataclass", ""]
    for name, spec in schema.items():
        lines += ["", "@dataclass(frozen=True)", f"class {name}:"]
        lines += [f"    {field}: {kind}" for field, kind in spec["fields"]]
        arguments = ", ".join(f"{field}=data[{field!r}]" for field, _ in spec["fields"])
        lines += ["", "    @classmethod", "    def from_json(cls, data):", f"        return cls({arguments})", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    schema = json.loads((ROOT / "api" / "orders.schema.json").read_text())
    (ROOT / "clients" / "orders_generated.py").write_text(generate(schema))
