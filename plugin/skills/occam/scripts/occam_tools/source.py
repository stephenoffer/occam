"""Reading source files: language detection, and separating code, strings and comments without a parser."""

from __future__ import annotations

import bisect
import json
import re
from pathlib import PurePosixPath
from typing import NamedTuple

EXTENSIONS = {
    ".py": "python", ".pyi": "python", ".ipynb": "notebook",
    ".js": "javascript", ".jsx": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".ts": "typescript", ".tsx": "typescript", ".mts": "typescript", ".cts": "typescript",
    ".vue": "javascript", ".svelte": "javascript",
    ".go": "go", ".rs": "rust", ".java": "java", ".kt": "kotlin", ".kts": "kotlin", ".scala": "scala",
    ".c": "c", ".h": "c", ".cc": "cpp", ".cpp": "cpp", ".cxx": "cpp", ".hpp": "cpp", ".hh": "cpp",
    ".cs": "csharp", ".swift": "swift", ".rb": "ruby", ".php": "php",
    ".sh": "shell", ".bash": "shell", ".zsh": "shell", ".sql": "sql", ".html": "html", ".htm": "html",
    ".dart": "dart", ".zig": "zig", ".m": "objective-c", ".mm": "objective-c", ".groovy": "groovy",
    ".ex": "elixir", ".exs": "elixir", ".r": "r", ".jl": "julia", ".pl": "perl", ".pm": "perl", ".ps1": "powershell", ".tf": "terraform",
    ".lua": "lua", ".erl": "erlang", ".hs": "haskell", ".clj": "clojure", ".ml": "ocaml", ".vb": "visualbasic", ".fs": "fsharp",
}
SHEBANGS = (("python", "python"), ("node", "javascript"), ("bash", "shell"), ("/sh", "shell"), ("env sh", "shell"), ("dash", "shell"), ("ksh", "shell"), ("/ash", "shell"), ("zsh", "shell"), ("ruby", "ruby"))
C_FAMILY = ("javascript", "typescript", "go", "rust", "java", "kotlin", "scala", "c", "cpp", "csharp", "swift", "php", "dart", "zig", "objective-c", "groovy")
HASH_FAMILY = ("elixir", "r", "julia", "perl", "powershell", "terraform")
# "Generated by ChatGPT" must not hide a file from a tool whose job is auditing AI-generated code. Only code generators count.
GENERATED_MARK = re.compile(r"code generated .{0,80}do not edit|@generated|(?:auto-?generated|generated (?:by|from|with)) (?:\S+ ){0,1}(?:protoc|thrift|swagger|openapi|sqlc|bindgen|grpc|flatc|mockgen|stringer|alembic|django|graphql-codegen|prisma)", re.I)
_COMMENT_START = re.compile(r"\s*(?:#|//|/\*|\*|--|<!--|;|%)")
TEST_PATH = re.compile(r"(^|/)(tests?|spec|specs|__tests__|testdata|test_support|e2e)/|(^|/)(test_[^/]+|[^/]+_(test|tests)\.\w+|[^/]+_spec\.(rb|js|jsx|mjs|cjs|ts|tsx|lua|coffee)|tests\.py|conftest\.py)$|\.(test|spec)\.\w+$|Tests?\.(java|kt|cs|swift)$")
# For what reaches what, the names above are enough. For a test's lighter checks they aren't: `lab_tests.py` and `run_tests.py` may be production code, and their secrets are real.
LIGHTER_CHECKS_PATH = re.compile(r"(^|/)(tests?|spec|specs|__tests__|testdata|test_support|e2e)/|(^|/)(test_[^/]+|[^/]+_test\.\w+|conftest\.py|(?:jest|vitest)\.setup\.\w+|setupTests\.\w+)$|\.(test|spec)\.\w+$|Tests?\.(java|kt|cs|swift)$")
SCRIPT_PATH = re.compile(r"(^|/)(scripts?|bin|tools?|examples?|docs?|benchmarks?|demos?|samples?|notebooks?|migrations?|fixtures?)/")
# Not code, so the rules don't read these, but a credential pasted into one is just as real. Only credential shapes run on them.
SECRETS_ONLY_FILE = re.compile(r"(^|/)(\.env(\.[^/]+)?|Dockerfile(\.[^/]+)?|[^/]+\.dockerfile|[^/]+\.(ya?ml|json|toml|tfvars|code-workspace)|requirements[^/]*\.(txt|in)|pip\.conf|CLAUDE\.md|AGENTS\.md|GEMINI\.md|SKILL\.md|\.cursorrules|\.windsurfrules|\.clinerules|copilot-instructions\.md|\.cursor/rules/[^/]+)$", re.I)
DOCKERFILE = re.compile(r"(^|/)(Dockerfile(\.[^/]+)?|[^/]+\.dockerfile)$", re.I)
_FIXTURE_PATH = re.compile(r"(^|/)(fixtures?|examples?|samples?|mocks?|__mocks__|__snapshots__|snapshots?|stubs?|testdata|test_data|docs?)/|\.(example|sample|template|tmpl|dist)(\.[^/]*)?$", re.I)


def language_of(path: str, head: str = "") -> str | None:
    language = EXTENSIONS.get(PurePosixPath(path).suffix.lower())
    if language or not head.startswith("#!"):
        return language
    first = head.split("\n", 1)[0]
    return next((name for needle, name in SHEBANGS if needle in first), None)


def is_test_path(path: str) -> bool:
    return bool(TEST_PATH.search(path))


def gets_test_checks(path: str) -> bool:
    return bool(LIGHTER_CHECKS_PATH.search(path))


def is_script_path(path: str) -> bool:
    return bool(SCRIPT_PATH.search(path))


def reads_only_for_secrets(path: str) -> bool:
    return bool(SECRETS_ONLY_FILE.search(path))


def is_fixture_path(path: str) -> bool:
    return is_test_path(path) or bool(_FIXTURE_PATH.search(path))


def says_it_is_generated(text: str) -> bool:
    """A code generator says so in a comment near the top. A string that says "do not edit" means nothing."""
    head = text[:2000].split("\n")[:12]
    return any(_COMMENT_START.match(line) and GENERATED_MARK.search(line) for line in head)


def looks_generated(text: str) -> bool:
    if says_it_is_generated(text):
        return True
    lines = text[:4000].split("\n")
    return bool(lines) and max(map(len, lines)) > 1500  # minified


_DOUBLE = r'"(?:\\.|[^"\\\n])*"'
_SINGLE = r"'(?:\\.|[^'\\\n])*'"
_TRIPLE = r'"""(?:\\.|[^\\])*?(?:"""|\Z)|\'\'\'(?:\\.|[^\\])*?(?:\'\'\'|\Z)'
_BACKTICK = r"`(?:\\.|[^`\\])*`"
_BLOCK = r"/\*.*?(?:\*/|\Z)"  # an unterminated comment runs to the end, so repeated openers stay linear
# A `/` opens a regex where a value is expected, and divides anywhere else. Bounded, so an unclosed one tried along a long line can't go quadratic.
_REGEX_LITERAL = r"(?P<r>(?:[=(,:;!&|?\[{\n]|=>|\breturn\b|\A)[ \t]*/(?![*/])(?:\\.|\[(?:\\.|[^\]\\\n]){0,100}\]|[^/\\\n\[]){1,300}/[a-zA-Z]*)"
_PATTERNS = {
    "python": rf"(?P<c>#[^\n]*)|(?P<s>[rRbBuUfF]{{0,2}}(?:{_TRIPLE}|{_DOUBLE}|{_SINGLE}))",
    "shell": rf"(?P<c>(?<![\w$#])#[^\n]*)|(?P<s>{_DOUBLE}|{_SINGLE})",
    "ruby": rf"(?P<c>#[^\n]*)|(?P<s>{_DOUBLE}|{_SINGLE})",
    "sql": rf"(?P<c>--[^\n]*|{_BLOCK})|(?P<s>{_SINGLE})",
    "rust": rf"(?P<c>//[^\n]*|{_BLOCK})|(?P<s>{_DOUBLE}|'(?:\\.|[^\\'\n])')",
    "go": rf"(?P<c>//[^\n]*|{_BLOCK})|(?P<s>{_DOUBLE}|{_BACKTICK}|'(?:\\.|[^\\'\n])+')",
    "html": r"(?P<c><!--.*?(?:-->|\Z))|(?P<s>\Zx)",
    "c_family": rf"(?P<c>//[^\n]*|{_BLOCK})|(?P<s>{_DOUBLE}|{_SINGLE}|{_BACKTICK})",
    "javascript": rf"(?P<c>//[^\n]*|{_BLOCK})|(?P<s>{_DOUBLE}|{_SINGLE}|{_BACKTICK})|{_REGEX_LITERAL}",
}
_PATTERNS["typescript"] = _PATTERNS["javascript"]
_COMPILED = {name: re.compile(pattern, re.S) for name, pattern in _PATTERNS.items()}
_NOT_NEWLINE = re.compile(r"[^\n]")


class Source(NamedTuple):
    path: str
    text: str
    language: str | None
    code: str           # comments and string contents blanked, same offsets
    comments: list      # (line, text)
    line_starts: list

    def line_of(self, offset: int) -> int:
        return bisect.bisect_right(self.line_starts, offset)

    def line_text(self, line: int) -> str:
        if not 1 <= line <= len(self.line_starts):
            return ""
        end = self.line_starts[line] - 1 if line < len(self.line_starts) else len(self.text)
        return self.text[self.line_starts[line - 1]:end]


def reads_comments(language: str | None) -> bool:
    return language in _COMPILED or language in C_FAMILY or language in HASH_FAMILY


def _blank(text: str) -> str:
    return _NOT_NEWLINE.sub(" ", text)


def load(path: str, text: str, language: str | None = None) -> Source:
    language = language or language_of(path, text[:200])
    starts = [0]
    find = text.find
    position = find("\n")
    while position >= 0:
        starts.append(position + 1)
        position = find("\n", position + 1)
    key = language if language in _COMPILED else "c_family" if language in C_FAMILY else "ruby" if language in HASH_FAMILY else None
    if key is None:
        return Source(path, text, language, text, [], starts)
    comments: list[tuple[int, str]] = []

    def replace(match: re.Match) -> str:
        chunk = match.group()
        if match.lastgroup == "c":
            comments.append((bisect.bisect_right(starts, match.start()), chunk))
            return _blank(chunk)
        if match.lastgroup == "r":  # what comes before the `/` is code, and only part of the match so as to place it
            opening = chunk.index("/") + 1
            return chunk[:opening] + _blank(chunk[opening:])
        quote = re.match(r"[a-zA-Z]{0,2}(\"\"\"|'''|\"|'|`)", chunk)
        width = len(quote.group()) if quote else 0
        tail = len(quote.group(1)) if quote else 0
        return chunk[:width] + _blank(chunk[width:len(chunk) - tail]) + chunk[len(chunk) - tail:]

    return Source(path, text, language, _COMPILED[key].sub(replace, text), comments, starts)


class Notebook(NamedTuple):
    python: str                  # all code cells as one virtual module
    line_map: list               # virtual line -> (cell number, line in cell)
    cells: list                  # raw cell dicts for code cells, with number
    raw_size_by_cell: dict
    output_text_by_cell: dict


_MAGIC = re.compile(r"^(\s*)([%!])")


def load_notebook(text: str) -> Notebook:
    document = json.loads(text)
    if not isinstance(document, dict) or not isinstance(document.get("cells", []), list):
        raise ValueError("not a notebook")
    lines: list[str] = []
    line_map: list[tuple[int, int]] = []
    cells = []
    sizes = {}
    outputs = {}
    for number, cell in enumerate(document.get("cells", []), start=1):
        if not isinstance(cell, dict) or cell.get("cell_type") != "code":
            continue
        body = cell.get("source", "")
        body = "".join(str(part) for part in body) if isinstance(body, list) else str(body)
        cells.append({"number": number, "source": body, "execution_count": cell.get("execution_count")})
        stored = json.dumps(cell.get("outputs", []))
        sizes[number] = len(stored)
        outputs[number] = stored
        for index, line in enumerate(body.split("\n"), start=1):
            lines.append(_MAGIC.sub(lambda m: m.group(1) + "# " + m.group(2), line))
            line_map.append((number, index))
    return Notebook("\n".join(lines) + "\n", line_map, cells, sizes, outputs)
