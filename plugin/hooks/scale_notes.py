"""Keeping occam in proportion at both ends: a one-line edit shouldn't pay for a long task's process, and a long run shouldn't lose its goal.

Pure decisions plus best-effort reads of the goal ledger. A hook must never fail because of anything here.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parents[1] / "skills" / "occam" / "scripts"
sys.path.insert(0, str(SCRIPTS))
TOOL = f"python3 {SCRIPTS / 'occam.py'}"

# What counts as small is deliberately narrow. Past any of these the usual hold applies, so the skill still arrives for real work.
SMALL_EDIT_LINES = 20  # from 186 saved runs: trivial-fix stayed small in 0 of 8 at 10 and 7 of 8 at 20, and substantial cases stayed out at 20. Development data
SMALL_EDIT_CHARS = 1_500
SMALL_SESSION_EDITS = 3
SMALL_SESSION_FILES = 2
LONG_RUN_EDITS = 30
LONG_RUN_FILES = 10
REWRITE_MIN_LINES = 30
CONSEQUENCE_CHARS = 200_000
SEND_BACKS_WITHOUT_A_PASS = 5

# Ordinary source files only. Configuration, infrastructure, lockfiles and SQL decide more than their size suggests.
SMALL_SUFFIXES = {".py", ".pyw", ".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx", ".mts", ".cts", ".go", ".rs", ".java", ".kt", ".kts", ".c", ".h", ".cc", ".cpp", ".cxx", ".hpp", ".hh",
                  ".rb", ".php", ".swift", ".cs", ".sh", ".bash", ".zsh", ".lua", ".pl", ".r", ".scala", ".dart", ".ex", ".exs", ".jl", ".hs", ".ml", ".clj", ".erl", ".m", ".mm", ".fs", ".zig",
                  ".html", ".htm", ".css", ".scss", ".vue", ".svelte"}
# Best effort, on purpose. No word list can decide what's consequential, and these don't have to: a wrong hold costs a skill load, and a miss
# leaves an edit under the rule card from session start, for an agent that judges this better than a pattern can.
NOT_SMALL_PATH = re.compile(r"auth|login|logout|passw|secret|token|credential|session|permission|rbac|(^|[/_.\-])(acl|iam|sso|prod)([/_.\-]|$)|tenan|billing|payment|invoice|checkout|refund|pricing|wallet|subscription"
                            r"|ledger|migrat|alembic|schema|database|(^|/)models?\.|settings|config|cors|crypto|encrypt|secur|admin|webhook|signature|saml|jwt|deploy|infra|terraform|k8s|kube|helm", re.I)
NOT_SMALL_PROMPT = re.compile(r"\b(secur\w*|o?auth\w*|log ?in|sign ?in|passw\w*|credential\w*|secret\w*|tokens?|jwt|sso|saml|sessions?|access control|acl|rbac|permission\w*|privilege\w*|encrypt\w*|decrypt\w*|crypto\w*"
                              r"|hash\w*|tls|ssl|certificate\w*|xss|csrf|inject\w*|vulnerab\w*|cve|pii|gdpr|sanitiz\w*|tenan\w*|admin\w*|payments?|billing|invoice\w*|refund\w*|checkout|money|currenc\w*|tax\w*|pric(e|es|ing)"
                              r"|migrat\w*|schema\w*|databases?|sql|quer(y|ies)|tables?|delete all|production|deploy\w*|rollback|concurren\w*|race|deadlock\w*|thread\w*|async\w*|locks?|locking"
                              r"|optimi[sz]\w*|efficien\w*|performance|latency|throughput|memory|slow\w*|faster|speed\w*|scal(e|es|ing|able|ability)"
                              r"|dependenc\w*|upgrade\w*|bump\w*|install\w*\s+(?!message|instructions|guide|docs?|script|steps?\b)\w+|refactor\w*|rewrite\w*|redesign\w*|architecture|breaking)\b", re.I)
NOT_SMALL_TEXT = re.compile(r"(?i:passw|secret|api_?key|credential|token|auth|login|logout|session|cookie|csrf|cors|permission|admin|is_staff|forbidden|verify\s*=|crypt|md5|sha\d|price|amount|balance|payment|invoice|refund|currency"
                            r"|sql|select\s+\S+\s+from|insert\s+into|delet|drop\b|drop_|truncate|alter\s+table|execute|\bquery)"
                            r"|\b(?:eval|exec|popen|spawn|sudo|chmod|chown|curl|wget|rm|rmtree|unlink|remove|rmSync|execSync|subprocess|pickle|socket|urllib|async|await|mutex|atomic|goroutine|unsafe|malloc|strcpy|sprintf|memcpy|innerHTML|dangerouslySetInnerHTML|Decimal)\b"
                            r"|\bos\.system|\bsystem\(|\brequests\.|\bfetch\(|\b[Tt]hread|\b[Ll]ock\b|\bopen\([^)\n]{0,200}['\"][wax]")
GENERATED_MARK = re.compile(rb"@generated|DO NOT EDIT|(?i:(code|file) generated by)|(?im:^\W*(auto-?)?generated)"
                            rb"|(?i:generated[^\n]*do not edit|do not edit[^\n]*generated)")
NOT_MEASURED_IN_LINES = {".ipynb", ".sql"}

_CLOSING_PASTE = re.compile(r"</pasted_content>", re.I)
_PASTE = re.compile(r"<pasted_content\b.*?</pasted_content>", re.S | re.I)


def without_pasted(prompt: str) -> str:
    """Removes pasted blocks. Nothing after the last closing tag can match, and letting the regex try is quadratic on unclosed tags."""
    end = max((match.end() for match in _CLOSING_PASTE.finditer(prompt)), default=0)
    return _PASTE.sub(" ", prompt[:end]) + prompt[end:]


def asked_for(stored: str) -> str:
    """A stored request without what was pasted. Storing cuts a long prompt short, which can take a paste's closing tag with it."""
    return re.sub(r"<pasted_content\b.*\Z", " ", without_pasted(stored), flags=re.S | re.I)


def _code_edits(entries: list[dict]) -> list[dict]:
    return [entry for entry in entries if entry.get("kind") == "edit" and entry.get("code")]


def small_edit(name: str, tool_input: dict, path: str, old: str, new: str) -> bool:
    """Is this one edit small? Anything that can't be sized isn't: a replace-all, a notebook cell, or a file too large to compare with what replaces it."""
    if tool_input.get("replace_all") or name == "NotebookEdit" or not (old or new):
        return False
    if name == "Write" and not old and os.path.exists(path) and os.path.getsize(path) > 0:
        return False
    return max(old.count("\n"), new.count("\n")) < SMALL_EDIT_LINES and len(old) + len(new) <= SMALL_EDIT_CHARS


def stays_small(entries: list[dict], paths: list[str]) -> bool:
    """Would the session's work still be small with this edit in it? A request that named something consequential stays named, whatever followed it."""
    edits = _code_edits(entries)
    return (len(edits) < SMALL_SESSION_EDITS and len({entry.get("path") for entry in edits} | set(paths)) <= SMALL_SESSION_FILES
            and not any(entry.get("kind") == "prompt" and entry.get("not_small") for entry in entries))


def is_consequential(relative: list[str], old: str, new: str, language_risk: str | None, entries: list[dict]) -> bool:
    """Does this edit touch something where mistakes cost most, whatever its size: the path, what it writes or removes, or what the request named?
    `language_risk` is what commonly goes wrong in this file's language."""
    if not relative or not all(Path(item).suffix.lower() in SMALL_SUFFIXES and not NOT_SMALL_PATH.search(item) for item in relative):
        return True
    if any(entry.get("kind") == "prompt" and entry.get("not_small") for entry in entries):  # a request that named something consequential stays named
        return True
    written = f"{old}\n{new}"  # taking something out can matter as much as putting it in
    if len(written) > CONSEQUENCE_CHARS:  # bounds the patterns' work, and an edit this large isn't ordinary anyway
        return True
    return bool(NOT_SMALL_TEXT.search(written) or (language_risk and re.search(language_risk, written, re.I)))


def is_small(name: str, tool_input: dict, path: str, relative: list[str], old: str, new: str, language_risk: str | None, entries: list[dict]) -> bool:
    """Is this edit, and the work so far, small and low consequence?"""
    if not small_edit(name, tool_input, path, old, new) or not stays_small(entries, relative):  # the size comes first, because it also bounds the patterns' work
        return False
    return not is_consequential(relative, old, new, language_risk, entries)


def replaces_working_code(cwd: str, name: str, tool_input: dict, file_path: str) -> bool:
    """True when this edit overwrites a substantial existing file, or a large part of one."""
    if name == "Write":
        path = Path(cwd, file_path)
        try:
            # is_file first: reading a FIFO would block until the hook's timeout.
            existing = path.read_text(encoding="utf-8", errors="replace") if path.is_file() else ""
        except OSError:
            return False
        return existing.count("\n") >= REWRITE_MIN_LINES
    return str(tool_input.get("old_string", "")).count("\n") >= REWRITE_MIN_LINES


def large_file_text(relative: str, data: bytes, limit: int, structure: str) -> str | None:
    """What to say about a very large source file, unless it's generated or isn't measured in lines. `structure` is where splitting one is covered, if anywhere."""
    lines = data.count(b"\n")
    if Path(relative).suffix.lower() in NOT_MEASURED_IN_LINES or lines <= limit or GENERATED_MARK.search(data[:600]):
        return None
    note = (f"occam: {relative} is {lines} lines, past the {limit} where a module is worth a second look. New code "
            "with its own responsibility belongs in its own module, though one more of a kind this file already holds can follow its siblings. Splitting what is already here is a separate change "
            "to propose, unless this request asks for it. A limit this repository configures takes precedence.")
    return note + (f" How to split safely is at {structure}." if structure else "")


def not_yet_said(missing: list[str], turn: list[dict]) -> list[str]:
    """What Stop hasn't already said about the code as it stands.

    This replaces `stop_hook_active`, which /goal sets too. It can't loop: with nothing changed there are only so many things to say, and without a check passing
    there are at most SEND_BACKS_WITHOUT_A_PASS, because some edits are only a command's output landing in a file. A pass starts the count again, so a long run keeps its checks.
    """
    sent = 0
    for entry in reversed(turn):
        if entry.get("kind") == "check" and entry.get("passed"):
            break
        sent += entry.get("kind") == "sent_back"
    if sent >= SEND_BACKS_WITHOUT_A_PASS:
        return []
    said: set[str] = set()
    for entry in reversed(turn):
        if entry.get("kind") == "edit" and entry.get("code"):
            break
        if entry.get("kind") == "sent_back":
            said.update(entry.get("said", []))
    return [complaint for complaint in missing if complaint not in said]


def recorded_goal(cwd: str | None) -> dict | None:
    try:
        from occam_tools import files, workflow
        return workflow._load(files.find_root(cwd or os.getcwd()))
    except Exception:  # occam: ignore[swallowed-exception] a reminder isn't worth failing a hook over
        return None


def goal_command() -> str:
    return f"{TOOL} goal"


def goal_reminder(cwd: str | None) -> str:
    """What compaction would otherwise lose: that a goal exists at all, and how far it has got."""
    goal = recorded_goal(cwd)
    if not goal:
        return ""
    requirements = goal.get("requirements", [])
    verified = sum(1 for requirement in requirements if requirement.get("status") == "verified")
    return (f" A goal is recorded: \"{str(goal.get('goal', ''))[:200]}\", with {verified} of {len(requirements)} requirements last verified. "
            f"`{goal_command()} status` prints it in full and `{goal_command()} verify` rechecks it. If it belongs to other work, `{goal_command()} clear` removes it.")


def is_long_run(entries: list[dict]) -> bool:
    edits = _code_edits(entries)
    return len(edits) >= LONG_RUN_EDITS or len({entry.get("path") for entry in edits if entry.get("path")}) >= LONG_RUN_FILES


def long_run_text(entries: list[dict], cwd: str | None, collaboration: str) -> str | None:
    """Said once. Compaction drops what isn't written down, so this is where recording the goal starts to pay for itself. A goal can be left over from other work, so it gets named, not assumed."""
    edits = _code_edits(entries)
    files = {entry.get("path") for entry in edits if entry.get("path")}
    goal = recorded_goal(cwd)
    if goal:
        return (f"occam: this has grown to {len(edits)} edits across {len(files)} files. A goal is recorded: \"{str(goal.get('goal', ''))[:200]}\". If that's this work, `{goal_command()} verify` rechecks it. "
                f"If not, `{goal_command()} init \"the observable outcome\"` replaces it, and it's what survives when a run outlasts its context.")
    return (f"occam: this has grown to {len(edits)} edits across {len(files)} files, and a run this long can outlast its context. `{goal_command()} init \"the observable outcome\"`, "
            f"then `goal add \"what must be true\" --check \"command\"`, records what done means where compaction can't reach it, and `goal verify` reruns those checks. "
            f"Finishing and checking one slice before the next keeps a failure small. More at {collaboration}.")
