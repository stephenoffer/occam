def test_a_stale_base_is_noticed_only_for_files_this_change_touches(tmp_path):
    upstream = repository(tmp_path / "upstream", {"a.py": "x = 1\n", "b.py": "y = 1\n"})
    clone = tmp_path / "clone"
    subprocess.run(["git", "clone", "-q", str(upstream), str(clone)], check=True, capture_output=True)
    write(upstream, {"a.py": "x = 2\n"})
    git(upstream, "commit", "-qam", "moved")
    git(clone, "fetch", "-q")
    write(clone, {"a.py": "x = 3\n"})
    assert "stale-base" in {note["rule"] for note in notes_on(clone)[0]}
    git(clone, "checkout", "-q", "--", "a.py")
    write(clone, {"b.py": "y = 2\n"})
    assert "stale-base" not in {note["rule"] for note in notes_on(clone)[0]}


