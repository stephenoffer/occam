@pytest.mark.parametrize("rule, base, bad, near_miss", CASES, ids=[f"{case[0]}-{index}" for index, case in enumerate(CASES)])
def test_each_check_speaks_on_the_bad_change_and_not_on_its_near_miss(rule, base, bad, near_miss, tmp_path):
    root = repository(tmp_path / "bad", base)
    write(root, bad)
    found, not_run = notes_on(root)
    assert rule in {note["rule"] for note in found}, (found, not_run)
    assert not not_run
    if near_miss is not None:
        other = repository(tmp_path / "near", base)
        write(other, near_miss)
        assert rule not in {note["rule"] for note in notes_on(other)[0]}


def test_these_warn_and_dont_block_the_gate(tmp_path):
    root = repository(tmp_path / "r", {"views.py": "@login_required\ndef a():\n    return 1\n", "vendor/x/a.go": "package a\n", "tests/test_views.py": "from views import a\n\ndef test_a():\n    assert a() == 1\n"})
    write(root, {"views.py": "def a():\n    return 1\n", "vendor/x/a.go": "package a\n// x\n"})
    text, code = verify.gate(root)
    assert code == 0 and "guard-removed" in text and "vendored-edited" in text and "warn  Reached everything it must" in text


def test_a_check_that_breaks_says_so_rather_than_passing_quietly(tmp_path):
    root = repository(tmp_path / "r", {"a.py": "x = 1\n"})
    write(root, {"a.py": "x = 2\n"})

    def broken(_change):
        raise AttributeError("no")
        yield

    found, not_run = change_checks.notes(root, None, filesystem.changed_lines(root, None), [], {}, True, (broken,))
    assert found == [] and not_run == ["broken"]


