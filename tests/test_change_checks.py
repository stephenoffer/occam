@pytest.mark.parametrize("rule, base, bad, near_miss", CASES, ids=[f"{case[0]}-{index}" for index, case in enumerate(CASES)])
def test_each_check_speaks_on_the_bad_change_and_not_on_its_near_miss(rule, base, bad, near_miss, tmp_path):
    root = repository(tmp_path / "bad", base)
    write(root, bad)
    found, not_run = notes_on(root)
    assert rule in {note["rule"] for note in found}, (found, not_run)
    assert not not_run
    if near_miss is not None:
        other = repository(tmp_path / "near", base)
        write(other, near_miss)
        assert rule not in {note["rule"] for note in notes_on(other)[0]}


