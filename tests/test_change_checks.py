def test_a_partial_read_runs_only_what_the_diff_can_settle():
    across_the_repository = set(change_checks.CHECKS) - set(change_checks.WITHIN_THE_DIFF)
    assert {change_checks._callers, change_checks._env_vars, change_checks._reach} <= across_the_repository
    assert set(change_checks.CHECKS[:len(change_checks.WITHIN_THE_DIFF)]) == set(change_checks.WITHIN_THE_DIFF), "the cheap ones run first, so running out of time drops the costly ones"
    assert change_checks._guards in change_checks.WITHIN_THE_DIFF


