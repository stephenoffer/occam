def git(root, *args):
    subprocess.run(["git", "-c", "user.email=a@b", "-c", "user.name=a", "-C", str(root), *args], check=True, capture_output=True)


def write(root, files):
    for name, text in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def repository(root, files):
    root.mkdir()
    git(root, "init", "-q")
    write(root, files)
    git(root, "add", "-A")
    git(root, "commit", "-qm", "base")
    return root


def notes_on(root):
    changed = filesystem.changed_lines(root, None) or {}
    deleted, renamed = filesystem.removed_and_renamed(root, None)
    return change_checks.notes(root, None, changed, deleted, renamed, True)


