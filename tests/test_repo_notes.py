def test_a_check_that_passed_and_now_fails_gets_a_note(agent):
    agent.edit()
    agent.bash("pytest -q", output="3 passed")
    agent.edit()
    assert "passed 1 code edit ago" in added(agent.bash("pytest -q", ok=False))


def test_a_check_failing_from_the_start_isnt_a_regression(agent):
    agent.edit()
    assert "code edit ago" not in (added(agent.bash("pytest -q", ok=False)) or "")


def test_the_same_command_failing_three_times_gets_a_note(agent):
    for _ in range(2):
        assert "exact command" not in (added(agent.bash("curl -f https://x.example/a", ok=False)) or "")
    assert "failed 3 times" in added(agent.bash("curl -f https://x.example/a", ok=False))


def test_an_edit_starts_the_count_again(agent):
    agent.bash("curl -f https://x.example/a", ok=False)
    agent.bash("curl -f https://x.example/a", ok=False)
    agent.edit()
    assert "exact command" not in (added(agent.bash("curl -f https://x.example/a", ok=False)) or "")


def test_a_pass_in_between_starts_the_count_again(agent):
    agent.bash("curl -f https://x.example/a", ok=False)
    agent.bash("curl -f https://x.example/a", ok=False)
    agent.bash("curl -f https://x.example/a")
    assert "exact command" not in (added(agent.bash("curl -f https://x.example/a", ok=False)) or "")


