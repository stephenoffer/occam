def git(agent, *args):
    subprocess.run(["git", "-c", "user.email=a@b", "-c", "user.name=a", "-C", str(agent.project), *args], check=True, capture_output=True)


def write(agent, name, text):
    path = agent.project / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return path


