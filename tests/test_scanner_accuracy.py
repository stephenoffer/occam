def findings(path: str, text: str, rule: str) -> list[dict]:
    return [f for f in scan.scan_text(path, text) if f["rule"] == rule]


def fires(path: str, text: str, rule: str) -> bool:
    return bool(findings(path, text, rule))


def scan_repo(tmp_path: Path, files: dict[str, str], *targets) -> scan.ScanResult:
    for name, text in files.items():
        target = tmp_path / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    return scan.run_scan(tmp_path, list(targets) or None, use_cache=False)


